function repo() {
  const root = mkdtempSync(join(tmpdir(), "cortex-v3-"));
  spawnSync("git", ["init", "-q", "-b", "main", root]);
  cortexInit(root, { node: process.execPath, cli: CLI, claudeHooks: false });
  return repoPaths(root);
}

test("v3 migration: v2 memories are archived word for word; generated files and blocks go; your own text and settings stay", () => {
  const root = mkdtempSync(join(tmpdir(), "cortex-mig-"));
  const p = repoPaths(root);
  mkdirSync(p.priv, { recursive: true });
  mkdirSync(join(root, ".claude", "rules"), { recursive: true });
  writeFileSync(join(p.vault, "ledger.jsonl"), '{"op":"add","text":"x"}\n');
  writeFileSync(join(p.vault, "INVARIANTS.md"), "<!-- Generated by Kapex Cortex -->\n# Project invariants\n- Never run docker.\n");
  writeFileSync(join(p.vault, "GRAVEYARD.md"), "<!-- Generated by Kapex Cortex -->\n# Failed approaches\n- async Stop hooks get killed.\n");
  writeFileSync(join(root, ".claude", "rules", "cortex-invariants.md"), "<!-- Generated by Kapex Cortex from .vault/ledger.jsonl. -->\n# Project invariants\n");
  writeFileSync(join(root, ".claude", "rules", "mine.md"), "# My own rule file\n");
  writeFileSync(join(root, "AGENTS.md"), "<!-- kapex-cortex:begin -->\nProject memory is kept by Kapex Cortex.\n<!-- kapex-cortex:end -->\n");
  writeFileSync(join(root, "CLAUDE.md"), "# Mine\nMy line.\n\n<!-- kapex-cortex-memory:begin (managed) -->\n- Use pnpm.\n<!-- kapex-cortex-memory:end -->\n");
  writeFileSync(join(p.priv, "managed.json"), JSON.stringify({ claude: ["Bash(docker:*)"], opencodeBash: [] }));
  mkdirSync(join(root, ".claude"), { recursive: true });
  writeFileSync(join(root, ".claude", "settings.local.json"), JSON.stringify({ permissions: { deny: ["Bash(docker:*)", "Bash(rm -rf:*)"] } }));
  const notes = migrateV2(p);
  assert.ok(notes.length >= 4, notes.join("; "));
  const archive = readFileSync(join(p.vault, "archive", "memories-v2.md"), "utf8");
  assert.match(archive, /- Never run docker\.[\s\S]*- async Stop hooks get killed\./);
  assert.ok(existsSync(join(p.vault, "archive", "ledger-v2.jsonl")) && !existsSync(join(p.vault, "ledger.jsonl")));
  assert.ok(!existsSync(join(root, ".claude", "rules", "cortex-invariants.md")) && existsSync(join(root, ".claude", "rules", "mine.md")));
  assert.ok(!existsSync(join(root, "AGENTS.md")), "an AGENTS.md that only held Cortex's pointer is removed");
  assert.equal(readFileSync(join(root, "CLAUDE.md"), "utf8"), "# Mine\nMy line.\n\n- Use pnpm.\n", "memories you moved into CLAUDE.md stay, markers go");
  assert.deepEqual(JSON.parse(readFileSync(join(root, ".claude", "settings.local.json"), "utf8")).permissions.deny, ["Bash(rm -rf:*)"], "only the deny v2 added is removed");
  assert.deepEqual(migrateV2(p), [], "runs once");
  assert.equal(computeStatus(p).migrated, ".vault/archive/memories-v2.md");
});

test("v3 native memory: Claude Code's files in load order, with paths-scoped rules, the auto memory 200-line cap and costs", () => {
  const p = repo();
  writeFileSync(join(p.root, "CLAUDE.md"), "# Rules\n- Use pnpm.\n");
  mkdirSync(join(p.root, ".claude", "rules"), { recursive: true });
  writeFileSync(join(p.root, ".claude", "rules", "api.md"), '---\npaths:\n  - "src/api/**"\n---\n\n- Validate every input.\n');
  const mem = autoMemory(p.root).dir;
  mkdirSync(mem, { recursive: true });
  writeFileSync(join(mem, "MEMORY.md"), Array.from({ length: 230 }, (_, i) => `- note ${i}`).join("\n") + "\n");
  writeFileSync(join(mem, "topic.md"), "---\nname: topic\ndescription: a topic\n---\n- detail\n");
  const files = nativeFiles(p.root);
  const by = (l: string) => files.find((f) => f.label === l)!;
  assert.equal(by("CLAUDE.md").loads, "always");
  assert.deepEqual(by("rules/api.md").paths, ["src/api/**"]);
  assert.equal(by("rules/api.md").tokens, 0, "path-scoped rules cost nothing until Claude touches those files");
  assert.equal(by("memory/MEMORY.md").loads, "first-200");
  assert.match(by("memory/MEMORY.md").over ?? "", /230 lines: only the first 200 load/);
  assert.equal(by("memory/topic.md").loads, "on-demand");
  assert.ok(nativeSummary(p.root).alwaysTokens > 0);
  // Claude Code's folder name: the absolute path with every other character as "-" (on Windows the drive comes first: D--Users-…)
  assert.equal(projectSlug("/Users/me/Claude Projects/app"), resolve("/Users/me/Claude Projects/app").replace(/[^A-Za-z0-9]/g, "-"));
  if (process.platform !== "win32") assert.equal(projectSlug("/Users/me/Claude Projects/app"), "-Users-you-Claude-Projects-app");
  assert.deepEqual(frontmatterPaths("---\npaths: [\"a/**\", 'b/*.ts']\n---\n"), ["a/**", "b/*.ts"]);
  assert.equal(frontmatterPaths("---\ndescription: x\n---\n"), undefined);
  const ents = entries("f", "f", "---\npaths: x\n---\n# H\n- one\n  continued\n- two\n\n```\n- not an entry\n```\nA paragraph\nthat wraps.\n");
  assert.deepEqual(ents.map((e) => [e.line, e.text]), [[5, "- one\n  continued"], [7, "- two"], [12, "A paragraph\nthat wraps."]]);
});

test("v3 hooks: Cortex adds nothing to messages; Stop writes the handoff; a new chat gets one line pointing at it", () => {
  const p = repo();
  const t = join(p.root, "t.jsonl");
  const ts = new Date(Date.now() - 20 * 60_000).toISOString();
  writeFileSync(t, JSON.stringify({ type: "user", uuid: "u1", timestamp: ts, message: { role: "user", content: "Build the export page" } }) + "\n");
  const hook = (name: string, input: object) => spawnSync(process.execPath, [CLI, "hook", name], { input: JSON.stringify({ cwd: p.root, session_id: "s1", transcript_path: t, ...input }), encoding: "utf8" });
  assert.equal(hook("claude.userpromptsubmit", { prompt: "rule: never do x" }).stdout, "", "no per-message injection, no capture of rules");
  assert.equal(hook("claude.stop", { last_assistant_message: "Plan:\n- [ ] write the page\nNext: build it" }).stdout, "");
  const st = readFileSync(statePath(p), "utf8");
  assert.match(st, /## Where we left off[\s\S]*Build the export page[\s\S]*Plan:/);
  assert.match(st, /## Open items\n- \[ \] write the page/);
  assert.doesNotMatch(st, /INVARIANTS|GRAVEYARD/);
  assert.equal(hook("claude.sessionstart", { session_id: "s2", source: "startup" }).stdout, "", "a handoff under 10 minutes old is this same stretch of work: no notice");
  const old = new Date(Date.now() - 30 * 60_000);
  utimesSync(statePath(p), old, old);
  const out = hook("claude.sessionstart", { session_id: "s2", source: "startup" }).stdout;
  assert.match(out, /^\{"hookSpecificOutput":\{"hookEventName":"SessionStart","additionalContext":"Kapex Cortex: A handoff packet \.vault\/STATE\.md exists/);
  assert.equal(hook("claude.sessionstart", { source: "compact" }).stdout, "", "after a compaction Claude Code reloads CLAUDE.md itself");
});

test("v3 handoff: the last exchanges word for word, active files and the last check; status preview counts them", () => {
  const p = repo();
  const plan = "## Plan\n| Phase | What |\n|---|---|\n| 1 | strip fix |\n- [ ] write the timeline tests\nNext: build Phase 1";
  saveExchange(p, "s", "first ask", "first reply");
  saveExchange(p, "s", "Give me the plan", plan);
  const ts = new Date().toISOString();
  accumulate(p, "s", [{ type: "user", timestamp: ts, message: { role: "user", content: "run it" } }, { type: "assistant", timestamp: ts, message: { content: [{ type: "tool_use", id: "a", name: "Edit", input: { file_path: join(p.root, "src/a.ts") } }, { type: "tool_use", id: "b", name: "Bash", input: { command: `cd "${p.root}" && npm run check > /tmp/out.txt 2>&1` } }] } }]);
  finalize(p, "s", plan);
  refreshState(p, { harness: "claude-code", session: "s", lastUser: "Give me the plan", lastAssistant: plan });
  const st = readFileSync(statePath(p), "utf8");
  assert.match(st, /### You[\s\S]*first ask[\s\S]*### You[\s\S]*Give me the plan[\s\S]*\| 1 \| strip fix \|/);
  assert.match(st, /## Active files\nEdited in the last turns: `src\/a\.ts`/);
  const pv = computeStatus(p).handoff.preview!;
  assert.deepEqual([pv.exchanges, pv.files, pv.openItems >= 2, /^npm run check passed/.test(pv.lastCheck)], [2, 1, true, true]);
});
