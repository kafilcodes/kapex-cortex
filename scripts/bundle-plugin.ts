// Copies the Cortex CLI (src/ + templates/) into claude-plugin/cortex/ so the plugin is self-contained:
// a plugin installed from GitHub only gets its own folder, and its hooks, MCP server and panel run
// `node ${CLAUDE_PLUGIN_ROOT}/cortex/src/cli.ts`. Generated: edit src/, then run `npm run bundle`.
// `--check` exits 1 if the copy is stale (npm test runs it), so a commit can't ship an old CLI.
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { skillFiles } from "../src/skills.ts";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "claude-plugin", "cortex");
const PARTS = ["src", "templates"];
const SKILLS = join(ROOT, "claude-plugin", "skills");
const PLUGIN_RUN = 'node "${CLAUDE_PLUGIN_ROOT}/cortex/src/cli.ts"';
/** The plugin's own skills: same text as the per-user ones, pointing at the bundled CLI. */
const pluginSkills = () => Object.entries(skillFiles("node", "", PLUGIN_RUN)).map(([n, t]) => [join("skills", n, "SKILL.md"), t] as const);
/** Git on Windows may check text out with CRLF: compare content, not line endings. */
const same = (a: string | undefined, b: string) => a !== undefined && a.replace(/\r\n/g, "\n") === b.replace(/\r\n/g, "\n");
const NOTE = "Generated by `npm run bundle` from src/ and templates/. Do not edit here.\n";

function files(dir: string): string[] {
  if (!existsSync(dir)) return [];
  return readdirSync(dir).flatMap((n) => {
    const p = join(dir, n);
    return statSync(p).isDirectory() ? files(p) : [p];
  });
}

export function stale(): string[] {
  const want = new Map<string, string>();
  for (const part of PARTS) for (const f of files(join(ROOT, part))) want.set(relative(ROOT, f), readFileSync(f, "utf8"));
  const have = new Map<string, string>();
  for (const part of PARTS) for (const f of files(join(OUT, part))) have.set(relative(OUT, f), readFileSync(f, "utf8"));
  const diff = [...want].filter(([k, v]) => !same(have.get(k), v)).map(([k]) => k);
  const skills = pluginSkills().filter(([rel, t]) => !existsSync(join(ROOT, "claude-plugin", rel)) || !same(readFileSync(join(ROOT, "claude-plugin", rel), "utf8"), t)).map(([rel]) => rel);
  return [...diff, ...[...have.keys()].filter((k) => !want.has(k)), ...skills];
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  if (process.argv.includes("--check")) {
    const s = stale();
    if (s.length) { console.error(`claude-plugin/cortex is stale (${s.slice(0, 5).join(", ")}). Run: npm run bundle`); process.exit(1); }
    console.log("claude-plugin/cortex is up to date");
  } else {
    for (const part of PARTS) { rmSync(join(OUT, part), { recursive: true, force: true }); cpSync(join(ROOT, part), join(OUT, part), { recursive: true }); }
    mkdirSync(OUT, { recursive: true });
    writeFileSync(join(OUT, "README.md"), NOTE);
    rmSync(SKILLS, { recursive: true, force: true });
    for (const [rel, t] of pluginSkills()) { mkdirSync(dirname(join(ROOT, "claude-plugin", rel)), { recursive: true }); writeFileSync(join(ROOT, "claude-plugin", rel), t); }
    console.log(`bundled ${PARTS.join(" + ")} into ${relative(ROOT, OUT)}`);
  }
}
