// Copies the Cortex CLI (src/ + templates/) into claude-plugin/cortex/ so the plugin is self-contained:
// a plugin installed from GitHub only gets its own folder, and its hooks, MCP server and panel run
// `node ${CLAUDE_PLUGIN_ROOT}/cortex/src/cli.ts`. Generated: edit src/, then run `npm run bundle`.
// `--check` exits 1 if the copy is stale (npm test runs it), so a commit can't ship an old CLI.
import { cpSync, existsSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import * as esbuild from "esbuild";
import { skillFiles } from "../src/skills.ts";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "claude-plugin", "cortex");
const PARTS = ["src", "templates"];
const SKILLS = join(ROOT, "claude-plugin", "skills");
const PLUGIN_RUN = 'node "${CLAUDE_PLUGIN_ROOT}/cortex/src/cli.ts"';
/** The plugin's own skills: same text as the per-user ones, pointing at the bundled CLI. */
/** /kc as a skill of the plugin only (not the per-user or OpenCode copies): listed from disk when a chat starts, so
 * Claude Desktop knows /kc at once; the plugin's command.run hook answers it with no model call (register.tsx). */
const KC_SKILL = `---
name: kc
description: Open the Kapex Cortex panel beside the chat.
---
Call the \`open_panel\` tool of the kapex-cortex plugin to open the Kapex Cortex panel, then reply with one short line saying it is open.
`;
/** The plugin's skills are all things you start yourself (/cortex-resume, /cortex-handoff, /cortex-init, /kc), so their
 * descriptions stay out of Claude's context: 0 tokens in every session instead of ~280 (`claude plugin details`).
 * Only the plugin's copies: OpenCode's own skill loader isn't asked to read a Claude Code key. */
const userOnly = (t: string) => t.replace(/^(---\n[\s\S]*?\n)---\n/, "$1disable-model-invocation: true\n---\n");
const pluginSkills = () => [...Object.entries(skillFiles("node", "", PLUGIN_RUN)), ["kc", KC_SKILL] as const].map(([n, t]) => [join("skills", n, "SKILL.md"), userOnly(t)] as const);
/** Git on Windows may check text out with CRLF: compare content, not line endings. */
const same = (a: string | undefined, b: string) => a !== undefined && a.replace(/\r\n/g, "\n") === b.replace(/\r\n/g, "\n");
const HOOK = join(OUT, "hook.mjs");
const STATUS = join(OUT, "src", "status.mjs");

/** The hooks run from one pre-built JavaScript file: Node's TypeScript stripping costs ~30 ms per hook launch plus
 * more per module, and Claude Code waits for every Stop hook. Built by esbuild (a dev tool only; nothing at runtime). */
function buildHook(outfile: string, entry = "hook.ts"): string {
  // esbuild's JS API: no shell, so no quoting differences between macOS, Linux and Windows
  esbuild.buildSync({ entryPoints: [join(ROOT, "src", entry)], bundle: true, platform: "node", format: "esm", target: "node22", outfile, logLevel: "warning",
    banner: { js: `// Generated by \`npm run bundle\` from src/${entry}. Do not edit here.` } });
  return readFileSync(outfile, "utf8");
}
/** The panel's `status --json` (after every reply) from one pre-built file next to cli.ts, for the same reason. */
const buildStatus = (outfile: string) => buildHook(outfile, "status-cli.ts");
const NOTE = "Generated by `npm run bundle` from src/ and templates/. Do not edit here.\n";

function files(dir: string): string[] {
  if (!existsSync(dir)) return [];
  return readdirSync(dir).flatMap((n) => {
    const p = join(dir, n);
    return statSync(p).isDirectory() ? files(p) : [p];
  });
}

export function stale(): string[] {
  const want = new Map<string, string>();
  for (const part of PARTS) for (const f of files(join(ROOT, part))) want.set(relative(ROOT, f), readFileSync(f, "utf8"));
  const have = new Map<string, string>();
  for (const part of PARTS) for (const f of files(join(OUT, part))) have.set(relative(OUT, f), readFileSync(f, "utf8"));
  const diff = [...want].filter(([k, v]) => !same(have.get(k), v)).map(([k]) => k);
  const skills = pluginSkills().filter(([rel, t]) => !existsSync(join(ROOT, "claude-plugin", rel)) || !same(readFileSync(join(ROOT, "claude-plugin", rel), "utf8"), t)).map(([rel]) => rel);
  const tmp = mkdtempSync(join(tmpdir(), "cortex-hook-"));
  let hook: string[] = [];
  try {
    hook = existsSync(HOOK) && same(readFileSync(HOOK, "utf8"), buildHook(join(tmp, "hook.mjs"))) ? [] : ["hook.mjs"];
    if (!existsSync(STATUS) || !same(readFileSync(STATUS, "utf8"), buildStatus(join(tmp, "status.mjs")))) hook.push("src/status.mjs");
  } finally { rmSync(tmp, { recursive: true, force: true }); }
  return [...diff, ...[...have.keys()].filter((k) => !want.has(k) && k !== join("src", "status.mjs")), ...skills, ...hook];
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  if (process.argv.includes("--check")) {
    const s = stale();
    if (s.length) { console.error(`claude-plugin/cortex is stale (${s.slice(0, 5).join(", ")}). Run: npm run bundle`); process.exit(1); }
    console.log("claude-plugin/cortex is up to date");
  } else {
    for (const part of PARTS) { rmSync(join(OUT, part), { recursive: true, force: true }); cpSync(join(ROOT, part), join(OUT, part), { recursive: true }); }
    mkdirSync(OUT, { recursive: true });
    writeFileSync(join(OUT, "README.md"), NOTE);
    buildHook(HOOK);
    buildStatus(STATUS);
    rmSync(SKILLS, { recursive: true, force: true });
    for (const [rel, t] of pluginSkills()) { mkdirSync(dirname(join(ROOT, "claude-plugin", rel)), { recursive: true }); writeFileSync(join(ROOT, "claude-plugin", rel), t); }
    console.log(`bundled ${PARTS.join(" + ")} into ${relative(ROOT, OUT)}`);
  }
}
