import { existsSync, mkdirSync, readFileSync, renameSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { atomicWriteIfChanged } from "../util/atomic.ts";
import type { RepoPaths } from "./paths.ts";

/**
 * v2 → v3, once per project, on the first hook or command that sees an old ledger. Cortex v3 keeps no memory store
 * of its own (Claude Code's CLAUDE.md, .claude/rules and auto memory do that job), so:
 *   - every v2 memory is archived, word for word, in .vault/archive/memories-v2.md (nothing is lost; copy what you
 *     still want into CLAUDE.md, or let a Dream sort it), and the ledger moves to .vault/archive/ledger-v2.jsonl
 *   - files Cortex generated are removed: .claude/rules/cortex-invariants.md, .vault/INVARIANTS.md, GRAVEYARD.md,
 *     and its copies for Cursor, Windsurf and Cline
 *   - Cortex's marked blocks come out of AGENTS.md and Copilot's file (copies); in CLAUDE.md, memories you moved
 *     there stay as your own lines, only the markers go
 *   - permission denies v2 compiled from rules (listed in .vault/private/managed.json) come out of
 *     .claude/settings.local.json and opencode.json; your own entries stay
 * Your own text is never changed.
 */
const GENERATED = /^<!-- Generated by Kapex Cortex/;
const OWN = [".cursor/rules/kapex-cortex.mdc", ".windsurf/rules/kapex-cortex.md", ".clinerules/kapex-cortex.md"];
const read = (f: string) => { try { return readFileSync(f, "utf8"); } catch { return null; } };

/** Remove a marked block; `keepInside` keeps its lines and drops only the markers. */
function unblock(file: string, begin: RegExp, end: RegExp, keepInside: boolean): boolean {
  const text = read(file);
  if (text === null) return false;
  const a = text.search(begin);
  if (a < 0) return false;
  const rest = text.slice(a);
  const m = end.exec(rest);
  if (!m) return false;
  const inner = rest.slice(rest.indexOf("\n") + 1, m.index);
  const out = (text.slice(0, a) + (keepInside ? inner : "") + rest.slice(m.index + m[0].length)).replace(/\n{3,}/g, "\n\n").trim();
  if (!out) rmSync(file, { force: true });
  else atomicWriteIfChanged(file, `${out}\n`);
  return true;
}

export function migrateV2(p: RepoPaths, now = new Date()): string[] {
  const ledger = join(p.vault, "ledger.jsonl");
  if (existsSync(p.marker) || !existsSync(ledger)) return [];
  const notes: string[] = [];
  const archive = join(p.vault, "archive");
  mkdirSync(archive, { recursive: true });
  const views = [join(p.vault, "INVARIANTS.md"), join(p.vault, "GRAVEYARD.md")].map((f) => read(f)).filter((t): t is string => !!t);
  const body = views.map((t) => t.replace(/^<!--.*-->\n/, "")).join("\n\n");
  writeFileSync(join(archive, "memories-v2.md"), `# Cortex v2 memories (archived ${now.toISOString().slice(0, 10)})\n\nCortex v3 no longer loads these. Claude Code's own CLAUDE.md, .claude/rules and auto memory do that job. Copy what you still want into CLAUDE.md, or run a Dream.\n\n${body || "_No views were found; the full history is in ledger-v2.jsonl._"}\n`);
  renameSync(ledger, join(archive, "ledger-v2.jsonl"));
  notes.push("archived v2 memories in .vault/archive/memories-v2.md");
  for (const f of [join(p.vault, "INVARIANTS.md"), join(p.vault, "GRAVEYARD.md"), join(p.vault, "PENDING.md")]) rmSync(f, { force: true });
  const rule = join(p.root, ".claude", "rules", "cortex-invariants.md");
  if (GENERATED.test(read(rule) ?? "")) { rmSync(rule, { force: true }); notes.push("removed .claude/rules/cortex-invariants.md (generated)"); }
  for (const f of OWN) if (existsSync(join(p.root, f))) { rmSync(join(p.root, f), { force: true }); notes.push(`removed ${f} (generated)`); }
  if (unblock(join(p.root, "AGENTS.md"), /<!-- kapex-cortex:begin -->/, /<!-- kapex-cortex:end -->\n?/, false)) notes.push("removed Cortex's pointer from AGENTS.md");
  for (const f of ["AGENTS.md", ".github/copilot-instructions.md"]) if (unblock(join(p.root, f), /<!-- kapex-cortex-memory:begin[^\n]*-->/, /<!-- kapex-cortex-memory:end -->\n?/, false)) notes.push(`removed Cortex's copy of memories from ${f}`);
  if (unblock(join(p.root, "CLAUDE.md"), /<!-- kapex-cortex-memory:begin[^\n]*-->/, /<!-- kapex-cortex-memory:end -->\n?/, true)) notes.push("CLAUDE.md: kept the memories you moved there, removed Cortex's markers");
  notes.push(...removeDenies(p));
  writeFileSync(p.marker, JSON.stringify({ version: 3, migratedAt: now.toISOString(), archive: ".vault/archive/memories-v2.md" }, null, 2) + "\n");
  return notes;
}

/** Take out exactly the denies v2 added (it recorded them in managed.json), nothing else. */
function removeDenies(p: RepoPaths): string[] {
  const notes: string[] = [];
  const managedFile = join(p.priv, "managed.json");
  let managed: { claude?: string[]; opencodeBash?: string[] } = {};
  try { managed = JSON.parse(readFileSync(managedFile, "utf8")) as typeof managed; } catch { /* none */ }
  const mine = new Set(managed.claude ?? []), oc = new Set(managed.opencodeBash ?? []);
  const claudeFile = join(p.root, ".claude", "settings.local.json");
  try {
    const s = JSON.parse(readFileSync(claudeFile, "utf8")) as { permissions?: { deny?: string[] } };
    const deny = s.permissions?.deny;
    if (deny && mine.size && deny.some((r) => mine.has(r))) {
      s.permissions!.deny = deny.filter((r) => !mine.has(r));
      atomicWriteIfChanged(claudeFile, JSON.stringify(s, null, 2) + "\n");
      notes.push(".claude/settings.local.json: removed the denies v2 added");
    }
  } catch { /* no settings file */ }
  const ocFile = join(p.root, "opencode.json");
  try {
    const cfg = JSON.parse(readFileSync(ocFile, "utf8")) as { permission?: unknown };
    let changed = false;
    if (Array.isArray(cfg.permission)) {
      const kept = (cfg.permission as { action?: string; resource?: string; effect?: string }[]).filter((r) => !(r.action === "shell" && r.effect === "deny" && oc.has(String(r.resource))));
      changed = kept.length !== cfg.permission.length;
      cfg.permission = kept;
    } else if (cfg.permission && typeof cfg.permission === "object") {
      const bash = (cfg.permission as { bash?: Record<string, string> }).bash;
      for (const k of Object.keys(bash ?? {})) if (oc.has(k) && bash![k] === "deny") { delete bash![k]; changed = true; }
    }
    if (changed) { atomicWriteIfChanged(ocFile, JSON.stringify(cfg, null, 2) + "\n"); notes.push("opencode.json: removed the denies v2 added"); }
  } catch { /* no OpenCode config */ }
  rmSync(managedFile, { force: true });
  rmSync(join(p.vault, "enforce.json"), { force: true });
  return notes;
}
